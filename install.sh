PAYLOAD_B64="$(printf '%s' "$PAYLOAD_B64" | tr -d '[:space:]')"

TMP=""
cleanup() { [ -n "$TMP" ] && rm -rf "$TMP"; }
trap cleanup EXIT

need_tmp() {
  [ -n "$TMP" ] || TMP="$(mktemp -d "${TMPDIR:-/tmp}/free-hive.XXXXXX")"
}

b64decode() {
  local out="$1" src="$TMP/payload.b64"
  printf '%s' "$PAYLOAD_B64" > "$src"
  base64 -d < "$src" > "$out" 2>/dev/null && return 0
  base64 -D < "$src" > "$out" 2>/dev/null && return 0
  base64 --decode < "$src" > "$out" 2>/dev/null && return 0
  openssl base64 -d -A -in "$src" -out "$out" 2>/dev/null && return 0
  echo "Nao consegui decodificar o payload (base64/openssl ausentes)." >&2
  return 1
}

unzip_to() {
  local zip="$1" dest="$2"
  mkdir -p "$dest"
  unzip -q "$zip" -d "$dest" 2>/dev/null || true
  [ -f "$dest/free-hive/index.ts" ] && return 0
  python3 -c 'import sys,zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$zip" "$dest" 2>/dev/null || true
  [ -f "$dest/free-hive/index.ts" ] && return 0
  tar -xf "$zip" -C "$dest" 2>/dev/null || true
  [ -f "$dest/free-hive/index.ts" ] && return 0
  echo "Nao consegui extrair o pacote (instale unzip ou python3)." >&2
  return 1
}

source_dir() {
  if [ -n "$HERE" ] && [ -f "$HERE/src/free-hive/index.ts" ]; then
    printf '%s\n' "$HERE/src/free-hive"
    return
  fi
  [ -n "$PAYLOAD_B64" ] || { echo "Payload embutido vazio: gere o instalador com build.ps1." >&2; exit 1; }
  need_tmp
  b64decode "$TMP/payload.zip"
  unzip_to "$TMP/payload.zip" "$TMP/x"
  [ -f "$TMP/x/free-hive/index.ts" ] || { echo "Payload invalido: index.ts ausente." >&2; exit 1; }
  printf '%s\n' "$TMP/x/free-hive"
}

resolve_agent_dir() {
  if [ -n "$AGENT_DIR" ]; then
    [ -d "$AGENT_DIR" ] || { echo "AgentDir nao existe: $AGENT_DIR" >&2; exit 1; }
    (cd "$AGENT_DIR" && pwd)
    return
  fi
  if [ -n "${PI_CODING_AGENT_DIR:-}" ] && [ -d "$PI_CODING_AGENT_DIR" ]; then
    (cd "$PI_CODING_AGENT_DIR" && pwd)
    return
  fi
  [ -d "$USERDATA" ] || { echo "Nao achei $USERDATA. Abra o DeepAI Code uma vez (com login) antes de instalar." >&2; exit 1; }

  local best="" best_time=0 dir time
  for dir in "$USERDATA"/*/pi/*; do
    [ -d "$dir" ] || continue
    if [ -f "$dir/models.json" ] || [ -d "$dir/sessions" ]; then
      time=$(stat -c %Y "$dir" 2>/dev/null || stat -f %m "$dir" 2>/dev/null || echo 0)
      if [ "$time" -ge "$best_time" ]; then best_time="$time"; best="$dir"; fi
    fi
  done
  if [ -n "$best" ]; then printf '%s\n' "$best"; return; fi
  printf '%s\n' "$USERDATA/deepai/pi/deepai"
}

show_model_check() {
  local dir="$1" file="$1/models.json" missing="" model
  if [ ! -f "$file" ]; then
    echo "Aviso: $file nao existe - o app ainda nao foi inicializado nesta maquina."
    echo "       Abra o DeepAI Code e faca login antes de usar o plugin."
    return
  fi
  for model in $EXPECTED_MODELS; do
    grep -q "\"$model\"" "$file" || missing="$missing $model"
  done
  if [ -z "$missing" ]; then
    echo "Catalogo OK: os 9 modelos gratuitos estao disponiveis."
  else
    echo "Aviso: modelos gratuitos ausentes nesta conta:$missing"
    echo "       O enxame usa os que existirem; '/hive models' mostra a lista."
  fi
}

